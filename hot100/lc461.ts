// 汉明距离
// 两个整数之间的汉明距离指的是这两个数字对应二进制位不同的位置的数目。
// 给你两个整数 x 和 y，计算并返回它们之间的汉明距离。
// 示例 1：
//   输入：x = 1, y = 4
//   输出：2
//   解释：
//     1   (0 0 0 1)
//     4   (0 1 0 0)
//              ↑   ↑
//     上面的箭头指出了对应二进制位不同的位置（第 1 位和第 2 位）
// 提示：0 <= x, y <= 2^31 - 1
// 进阶：有很多办法可以解决此题：内置函数 popcount（如 C++ 的 __builtin_popcount）、
//       位移、n & (n - 1) 等，请尝试用这些思路自己实现。
const hammingDistance = (x: number, y: number): number => {
  let res = x ^ y;
  let count = 0;
  while (res !== 0) {
    res = res & (res - 1);
    count++;
  }
  return count;
};
// 时间复杂度 O(1) —— 循环次数 = 异或结果中 1 的个数 ≤ 31（x, y ≤ 2^31-1），常数
// 空间复杂度 O(1) —— 只用了两个变量
//
// ── 本题总结 ────────────────────────────────────────────────────
// 要点           │ 内容
// ──────────────┼────────────────────────────────────────────────
// 核心洞察       │ 汉明距离 = 异或结果中 1 的个数：异或规则是"相同得 0、
//                │ 不同得 1"，它把"逐位比较"改写成了"数 1"
// 为什么是异或   │ 与(&) 和 或(|) 都不行：& 只留下"两个都是 1"的位，
//                │ | 只留下"至少一个 1"的位，都无法表达"不相同"
//                │ → 异或是唯一一个"不同才算账"的位运算
// 改写问题       │ 汉明距离(x, y) = 数1(x ^ y)，子问题退化到 lc338 学过的"数 1"
// 数 1 方法二    │ n & (n-1) 每次抹掉最低位的 1（如 1010 & 1001 = 1000），
//                │ 循环次数 = 1 的个数，不需要逐位检查了
// 与 lc338 的联系│ 338 给每个数算 1 的个数（递推表）；461 给两个数的差异位
//                │ 算个数（现数）。共同工具：位运算 + 数 1
// 其他解法       │ ① 逐位检查：for i in 0..31 累加 ((x>>i)&1) ^ ((y>>i)&1)
//                │ ② JS 内置做法：x ^ y 后 toString(2) 数 '1'（面试中提一句
//                │    C++ 的 __builtin_popcount 即可，不必真用）
// 小注           │ res = res & (res - 1) 可写为 res &= res - 1，等价且更地道

