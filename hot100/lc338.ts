// 比特位计数
// 给你一个整数 n，对于 0 <= i <= n 中的每个 i，计算其二进制表示中 1 的个数，
// 并返回一个长度为 n + 1 的数组 ans 作为答案。
// 示例 1：
//   输入：n = 2
//   输出：[0, 1, 1]
//   解释：0 --> 0, 1 --> 1, 2 --> 10
// 示例 2：
//   输入：n = 5
//   输出：[0, 1, 1, 2, 1, 2]
//   解释：0 --> 0, 1 --> 1, 2 --> 10, 3 --> 11, 4 --> 100, 5 --> 101
// 提示：0 <= n <= 10^5
// 进阶：很容易就能实现时间复杂度为 O(n log n) 的解决方案。
//       你可以在线性时间复杂度 O(n) 内用一趟扫描解决此问题吗？
//       要求算法的空间复杂度为 O(n)。（不使用任何内置函数，如 __builtin_popcount）
const countBits = (n: number): number[] => {
  const ans = new Array(n + 1).fill(0);
  // 此时ans[0]就是0，不用额外初始化了
  for (let i = 1; i < n + 1; i++) {
    ans[i] = ans[i >> 1] + (i & 1);
  }
  return ans;
};

// 时间复杂度 O(n) —— 一趟扫描，每个格子只做一次 O(1) 查表+加法
// 空间复杂度 O(n) —— ans 数组
//
// ── 本题总结 ────────────────────────────────────────────────────
// 要点           │ 内容
// ──────────────┼────────────────────────────────────────────────
// 核心洞察       │ 递推代替重数：每个 ans[i] 从"二进制只差一位"的前驱变出来
// 为什么是 i>>1  │ i>>1 就是 i 去掉最低位剩下的部分（二进制"少最后一位"），
//                │ 所以 i = 2·(i>>1) + 最低位，两者结构上只差这一位
//                │ → 递推代价 = 只检查这一位，其余直接抄前驱的答案
// 为什么不是 i-1 │ 减 1 会引发一连串进位翻掉好几位（8→7：1000→0111 翻 3 位），
//                │ 翻转规律取决于低位连续的 0 有多少，没有"只看一位就能补"的关系
// 为什么是 i&1   │ i&1 取最低位（奇数 1 / 偶数 0），恰好是 i 比 i>>1 多的那一位
// 递推式         │ ans[i] = ans[i >> 1] + (i & 1)
// 地基           │ ans[0] = 0；循环从 i = 1 开始
//                │ （i = 0 时 i>>1 = 0，会 ans[0] = ans[0] + 0 自己指自己，套牢）
// 对比朴素法     │ 每个数现场数 1（÷2 看余数）→ O(n log n)；递推一趟 → O(n)
// 复杂度         │ 时间 O(n)，空间 O(n)
// 变体（可收藏） │ ans[i] = ans[i & (i-1)] + 1：i&(i-1) 抹掉最低位的 1，
//                │ 抹完后的数更小且答案已知，+1 补回被抹掉的那个 1
//                │ （呼应"数 1"方法二：n & (n-1) 每次消掉一个 1）
