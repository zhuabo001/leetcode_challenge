// 完全平方数
// 给你一个整数 n ，返回 和为 n 的完全平方数的最少数量 。
// 完全平方数 是一个整数，其值等于另一个整数的平方；换句话说，其值等于一个整数自乘的积。例如，1、4、9 和 16 都是完全平方数，而 3 和 11 不是。

const numSquares = (n: number): number => {
  const dp = new Array(n + 1 /**如果用n的话下标是0-n-1，会越界 */).fill(
    Infinity
  ); // dp[i]代表和为i需要的完全平方数最少为dp[i]个

  dp[0] = 0;

  for (let i = 1; i <= n; i++) {
    for (let j = 1; j * j <= i; j++) {
      dp[i] = Math.min(dp[i], dp[i - j * j] + 1);
    }
  }
  return dp[n];
};
// 时间复杂度 O(n√n) —— 外层循环 n 次，内层 j 满足 j*j <= i，最多 √n 次
// 空间复杂度 O(n) —— dp 数组长度 n+1
//
// ── 本题总结 ────────────────────────────────────────────────────
// 要点        │ 内容
// ───────────┼──────────────────────────────────────────────────
// 问题转化    │ 完全平方数 = 零钱兑换(lc322)变体，"硬币面额"为 1,4,9,… 需自己生成
// 状态定义    │ dp[i] = 和为 i 所需完全平方数的最少个数
// 转移方程    │ dp[i] = min(dp[i - j*j] + 1)，j 从 1 到 j*j <= i
// 与lc322区别 │ 1 永远是完全平方数 → 一定可达 → 无需判断 Infinity 返回 -1
// 易错点      │ 数组长度要 n+1（下标 0~n）；内层是循环取 min，不是两值 min
// 复杂度      │ 时间 O(n√n)，空间 O(n)
