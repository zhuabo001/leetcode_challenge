// 10. 正则表达式匹配
// https://leetcode.cn/problems/regular-expression-matching/
// 给你一个字符串 s 和一个字符规律 p，请你来实现一个支持 '.' 和 '*' 的正则表达式匹配。
// '.' 匹配任意单个字符
// '*' 匹配零个或多个前面的那一个元素
// 所谓匹配，是要涵盖 整个 字符串 s 的，而不是部分字符串。
// 说明: s 可能为空，且只包含从 a-z 的小写字母。p 可能为空，且只包含从 a-z 的小写字母，以及字符 . 和 *。
const isMatch = (s: string, p: string): boolean => {
  const dp = new Array(s.length + 1)
    .fill(false)
    .map(() => new Array(p.length + 1).fill(false));
  dp[0][0] = true;
  for (let i = 0; i <= s.length; i++) {
    for (let j = 1; j <= p.length; j++) {
      // 情况1: p[j]是普通字符
      if (p[j - 1] !== '*') {
        if (i > 0) {
          dp[i][j] =
            dp[i - 1][j - 1] && (s[i - 1] === p[j - 1] || p[j - 1] === '.');
        }
      } else {
        // 情况2: p[j]是*号

        dp[i][j] =
          dp[i][j - 2] ||
          (i > 0 /** 边界守卫， 放置i=0时dp[i-1]越界 */ &&
            dp[i - 1][j] &&
            (s[i - 1] === p[j - 2] || p[j - 2] === '.'));
      }
    }
  }
  return dp[s.length][p.length];
};
// 时间复杂度 O(m·n) —— m = |s|, n = |p|；双层循环填 dp 表，每格 O(1)
// 空间复杂度 O(m·n) —— dp 二维表（两串长度都记为 N 时即为 O(N²)）
//
// ── 本题总结 ────────────────────────────────────────────────────
// 要点           │ 内容
// ──────────────┼────────────────────────────────────────────────
// 核心洞察       │ '*' 能匹配"零个"→ 面对 c* 时手里有"跳过"这张牌，
//                │ 匹配变成一棵决策树 → 找一条能走通的路 = DP
// 状态定义       │ dp[i][j]：p 的前 j 个字符能否匹配 s 的前 i 个字符（boolean）
// 递推式（情况一）│ p[j-1] 是普通字符或 '.'（必须消费一个）：
//                │   dp[i][j] = dp[i-1][j-1] && (s[i-1]==p[j-1] || p[j-1]=='.')
// 递推式（情况二）│ p[j-1]=='*'（c = p[j-2]）：
//                │   选择一（跳过）: dp[i][j-2]
//                │   选择二（消费）: i>0 && dp[i-1][j] && (s[i-1]==c || c=='.')
//                │   dp[i][j] = 选择一 || 选择二
// 为什么 i 从 0  │ 空串也是合法状态：dp[0][j] 必须被递推填出
// 开始            │ （如 "a*" 匹配空串：dp[0][2] = dp[0][0] = true，选择一链）
// 守卫的位置      │ 情况一、选择二访问 dp[i-1][*] → i=0 越界，加 i>0
//                │ 但守卫只能包"越界那一项"：选择一（跳过）i=0 时照样要走
// 方法论         │ 字符串匹配类 DP：盯着 p 的最后一个字符分类讨论
//                │ （lc72 编辑距离、lc1143 最长公共子序列同款套路）
// 踩坑记录       │ ① 外层 i 从 1 写起 → 空串整行没填 ② 守卫放错范围 →
//                │ 选择一连坐挡死。教训：先想清代码路径再放守卫
// 复杂度         │ 时间 O(m·n)，空间 O(m·n)

