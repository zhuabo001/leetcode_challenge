// 位运算笔记：删 / 看 / 掩码
//
// 三兄弟最容易混，放一起对照（来自 lc338 与 lc461 的讨论）：
//
// 操作          │ 学名           │ 干什么              │ 例子                    │ 出现在
// ─────────────┼────────────────┼─────────────────────┼─────────────────────────┼────────
// i >> 1       │ 右移一位       │ 删（扔）掉最低位     │ 7(111) → 3(11)          │ lc338
// i & 1        │ 与掩码 1       │ 看（读）最低位       │ 7&1=1，6&1=0            │ lc338
// n & (n-1)    │ 抹掉最低位的1  │ 删掉最低位的那个 1   │ 10(1010) → 8(1000)      │ lc461
// x ^ y        │ 异或           │ 不同得 1，相同得 0   │ 1^4 = 5(0101) → 2 个 1  │ lc461
//
// 怎么记：
// - 1 当掩码 → 只看第 0 位（结果只能是 0 或 1，什么都不删）
// - >> 1     → 扔掉第 0 位（数字本身少一位，变小的同时信息丢失）
// - n-1 当掩码→ 删掉最低位的那个 1（不管这个 1 在第几位，中间的 0 原样保留）
// - 配套使用：i = (i>>1)×2 + (i&1) —— 拆走什么、补回什么，严丝合缝
//
// 实战怎么选：
// - 要"数 1"（lc461 / lc191）：n & (n-1)，循环几次就是几个 1
// - 要"递推查表"（lc338）：i>>1 造更小的前驱 + i&1 补回被删的位
// - 要"找差异位"（lc461 / lc136）：x ^ y，不同位自动聚成 1
