// 不同的二叉搜索树
// 给你一个整数 n ，求恰由 n 个节点组成且节点值从 1 到 n 互不相同的 二叉搜索树 有多少种？返回满足题意的二叉搜索树的种数。

const kindsOfBST = (n: number): number => {
  // 由你来写
  // 确定状态转移方程
  // 初始化dp数组
  // 确定遍历方向
  // 举例推导dp数组
  const dp = new Array(n + 1).fill(0);
  dp[0] = 1;
  dp[1] = 1;
  dp[2] = 2;
  for (let i = 3; i <= n; i++) {
    for (let j = 1; j <= i; j++) {
      dp[i] +=
        dp[j - 1] /**左子树有j-1个节点 */ * dp[i - j] /** 右子树有i-j个节点 */;
    }
  }
  return dp[n];
};

// 题解：
// dp[i] 表示由连续的 i 个数字（1...i）能构造出的不同 BST 的数量
//
// 核心思路：任选一个数字 j 作为根节点
//   - 左子树有 j-1 个节点（比 j 小的数字）
//   - 右子树有 i-j 个节点（比 j 大的数字）
//   左右两侧独立组合，所以 dp[j-1] × dp[i-j]
//   遍历 j = 1...i 作为根，累加所有组合数
//
// 状态转移方程：dp[i] = Σ_{j=1}^{i} dp[j-1] × dp[i-j]
// 初始值：dp[0] = 1（空树也算一种结构），dp[1] = 1
//
// 时间复杂度 O(n²) — 两层循环
// 空间复杂度 O(n) — dp 数组
//
// 这个数列就是卡特兰数（Catalan Number）：C₀=1, Cₙ₊₁ = Σ Cᵢ·Cₙ₋ᵢ
