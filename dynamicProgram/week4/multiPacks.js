// 多重背包问题
// 有N种物品和一个容量为V的背包。第i种物品最多有Mi件可用，每件耗费的空间是Ci，价值是Wi。求解将哪些物品装入背包可使这些物品的耗费的空间 总和不超过背包容量，且价值总和最大。
// 输入：
// 第一行：两个整数，N（物品数量）和V（背包容量），用空格隔开。
// 接下来的N行，每行三个整数Ci,Wi,Mi，用空格隔开，分别表示第i种物品的费用、价值和数量。
// 输出：
// 输出一个整数，表示最大价值。
// 示例：
// 输入：
// 4 5
// 1 2 3
// 2 4 1
// 3 4 3
// 4 5 2
// 输出：
// 10
// 解释：
// 第1件物品选3件，第2件物品选1件，第3件物品选3件，第4件物品选2件，总价值为10。
const multiPacks = (N, V, C, W, M) => {
  // 1. 确定dp[i][j]的含义：表示前i种物品在容量为j的背包中能够获得的最大价值
  // 2. 确定状态转移方程： dp[i][j] = Math.max(dp[i-1][j], dp[i-1][j-C[i]] + W[i], dp[i-1][j-2*C[i]] + 2*W[i], ..., dp[i-1][j-M[i]*C[i]] + M[i]*W[i])
  // 3. 初始化dp数组：dp[0][j] = 0, dp[i][0] = 0
  // 4. 遍历顺序：先遍历物品，再遍历背包容量
  // 5. 返回dp[N][V]
  const dp = Array.from({ length: N + 1 }, () => Array(V + 1).fill(0));
  dp[0][0] = 0;
  for (let i = 1; i <= N; i++) {
    for (let j = 1; j <= V; j++) {
      for (let k = 0; k <= M[i]; k++) {
        if (j >= k * C[i]) {
          dp[i][j] = Math.max(dp[i][j], dp[i - 1][j - k * C[i]] + k * W[i]); // 第i件物品选k件
        }
      }
    }
  }
  return dp[N][V];
};
