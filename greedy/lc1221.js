// 1221. 分割平衡字符串
// 在一个 平衡字符串 中，'L' 和 'R' 字符的数量是相同的。
// 给你一个平衡字符串 s，请你将它分割成尽可能多的平衡字符串。
// 注意：分割得到的每个字符串都必须是平衡字符串。
// 返回可以通过分割得到的平衡字符串的 最大数量 。

// 示例1:
// 输入：s = "RLRRLLRLRL"
// 输出：4
// 解释：s 可以分割为 "RL"、"RRLL"、"RL"、"RL" ，每个子字符串中都包含相同数量的 'L' 和 'R' 。

// 示例2:
// 输入：s = "RLLLLRRRLR"
// 输出：3
// 解释：s 可以分割为 "RL"、"LLLRRR"、"LR" ，每个子字符串中都包含相同数量的 'L' 和 'R' 。

// 示例3:
// 输入：s = "LLLLRRRR"
// 输出：1
// 解释：s 只能保持原样 "LLLLRRRR".

const balancedStringCount = (str) => {
  // 关键点：原字符串本身是平衡的 -> l和r的个数是一样的
  // 分割后的每个子串也必须是平衡的
  // 目标是最大化分割的数量
  // 核心思路： 一旦遇到一个平衡子串就立刻分割，不要等待更长的平衡串
  // 为什么这样是正确的？
  //  - 如果当前子串已经平衡（L和R数量相等），继续往后扩展只会让子串变长，而不会增加分割数量
  //  - 尽早分割可以留下更多的字符给后续的分割，从而最大化总数
  let count = 0;
  let tempCount = 0;
  for (const char of str) {
    if (char === 'R') tempCount++;
    if (char === 'L') tempCount--;
    if (tempCount === 0) count++;
  }
  return count;
};
// 复杂度分析：
//    - 时间复杂度：O(n)，只需遍历一次字符串
//    - 空间复杂度：O(1)，只用了两个变量

